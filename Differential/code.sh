#!/usr/bin/env bash
# Writes Code.lean: the code bytes of the memrchr variants, copied out of libc.a's members (run `bash get-libc.sh`
# first) and the fixed objects. `--check` regenerates into a temporary file and compares.
set -euo pipefail
here=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
glibc="$here/../glibc-2.43-ubuntu-26.04-amd64"
work=$(mktemp -d)
trap 'rm -rf -- "$work"' EXIT
(cd "$work" && ar x "$glibc/libc.a" memrchr-sse2.o memrchr-avx2.o memrchr-evex.o)

emit() { # name object section description
  objcopy -O binary --only-section="$3" "$2" "$work/$1.bin"
  printf '\n/-- %s (%d bytes). -/\ndef %s : List Byte :=\n  [' "$4" "$(stat -c %s "$work/$1.bin")" "$1"
  od -An -v -tx1 "$work/$1.bin" | tr -s ' \n' ' ' | sed 's/^ //; s/ $//; s/\([0-9a-f][0-9a-f]\)/0x\1,/g; s/,$//' |
    fold -w 96 -s | sed '2,$s/^/  /; s/ $//'
  printf ']\n'
}

{
  cat <<'EOF'
import ZellicX86.Spec.Word
/-!
# The code of glibc 2.43's `memrchr` variants

Generated by `code.sh` from Ubuntu 26.04's `libc.a` (`get-libc.sh`) and `fixed/`; `code.sh --check` compares. Each
function is its object's code section, position independent (no relocation in it).
-/
namespace Differential.Code
open ZellicX86
EOF
  emit sse2 "$work/memrchr-sse2.o" .text '`__memrchr_sse2`, `libc.a` `memrchr-sse2.o`'
  emit avx2 "$work/memrchr-avx2.o" .text.avx '`__memrchr_avx2`, `libc.a` `memrchr-avx2.o`'
  emit evex "$work/memrchr-evex.o" .text.evex '`__memrchr_evex`, `libc.a` `memrchr-evex.o`'
  emit evexFixed "$glibc/fixed/memrchr-evex-fixed.o" .text.evex '`__memrchr_evex` with the `subq` fix, `fixed/memrchr-evex-fixed.o`'
  emit avx2Fixed "$glibc/fixed/memrchr-avx2-fixed.o" .text.avx '`__memrchr_avx2` with the `jb` fix, `fixed/memrchr-avx2-fixed.o`'
  printf '\nend Differential.Code\n'
} > "$work/Code.lean"

if [ "${1:-}" = --check ]; then
  diff -u "$here/Code.lean" "$work/Code.lean" && echo 'code.sh: Code.lean matches the objects'
else
  mv "$work/Code.lean" "$here/Code.lean"
fi
